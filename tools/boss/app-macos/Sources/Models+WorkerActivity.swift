import Foundation
import PaneLayout

// ===========================================================================
// Live worker state. `WorkerLiveState` is the per-worker snapshot the app polls
// for, and `AgentActivityState` is the derived, human-readable activity line the
// agents pane renders from it. Split out of Models.swift to keep that file under
// the repo's file-size check.
// ===========================================================================

/// Live runtime state for one allocated worker slot, mirroring the
/// engine's `LiveWorkerState`. Keyed by `slotId` (1..=16) — survives
/// run-record finalisation, which happens within a second of spawn.
struct WorkerLiveState {
    var name: String? = nil

    var displayName: String {
        Self.displayName(name: name, runId: runId)
    }

    static func displayName(name: String?, runId: String) -> String {
        guard let name, !name.isEmpty else { return "Worker \(runId)" }
        return name
    }

    let slotId: Int
    let runId: String
    let model: String
    let shellPid: Int32
    /// ISO-8601 timestamp of the most recent hook event. Deliberately
    /// excluded from `==`/`hash(into:)` below — see the note there.
    let lastEventAt: String?
    let currentTool: String?
    /// ISO-8601 timestamp of the most recent `PostToolUse`. Deliberately
    /// excluded from `==`/`hash(into:)` below — see the note there.
    let lastToolEndedAt: String?
    let activity: WorkerActivity
    /// Free-text one-sentence description of what the worker is doing
    /// right now, generated by the engine's `live_status` summarizer
    /// from a tail of the transcript. `nil` while spawning, idle long
    /// enough for the prior text to have been cleared, or before the
    /// first summary lands. Rendered as the Doing-card subtitle and
    /// the Agents-tab worker header subtitle.
    let liveStatus: String?
    /// ISO-8601 timestamp of the most recent successful update to
    /// `liveStatus`. Used by the UI to dim stale values.
    let liveStatusAt: String?
    /// Set by the engine's transient-recovery sweep while this slot is
    /// being auto-resumed after a transient Claude API error (529/5xx/
    /// network), e.g. "recovering from API error (attempt 2/5)". Takes
    /// display priority over `liveStatus` — see `AgentActivityState`
    /// and the Doing-card / pane-titlebar subtitle. `nil` once the
    /// worker's next hook event proves it resumed, or once the slot is
    /// released.
    let recoveryStatus: String?
    let hungSince: String?
    /// Mirrors the engine's `LiveWorkerState.tmux_hosted`: `true` for a
    /// local worker hosted in a tmux session. `nil` when the engine hasn't
    /// reported it — remote SSH workers, which remain valid without a
    /// local tmux identity. `false` is a local invariant failure (the
    /// durable tmux stamp is missing), not a supported hosting mode.
    let tmuxHosted: Bool?
    /// Reason the worker declared via `boss propose wait`, if an unexpired
    /// wait is currently holding the produce-a-PR nudge ladder.
    let waitReason: String?
    /// ISO-8601 expiry of that wait, when one is set.
    let waitExpiresAt: String?
    /// Wire badge type (`"coding"`, `"review"`, …). Missing or unrecognised
    /// values render as Unknown; they are never dropped from membership.
    let agentType: String?
    /// Engine-reported stage of an AI review (`"reviewers"` or
    /// `"consolidation"`); `nil` for non-review runs and older engines.
    let reviewStage: String?
    /// Durable execution kind reported by the engine.
    let executionKind: String?
    let projectId: String?
    let projectName: String?
    /// Host the run executes on. Agents membership is
    /// `hostId == WorkerLiveState.localHostId`; remote workers stay out.
    let hostId: String?
    /// ISO-8601 execution start; the Agents grid sorts by this then `runId`.
    let startedAt: String?
    /// Attributed pool: `"main"`, `"automation"`, or `"review"`. Independent
    /// of the physical slot — spilled automation still reports `"automation"`.
    let pool: String?
    /// Mirrors the engine's `LiveWorkerState.viewer_attach_error`: why the
    /// engine's most recent attempt to attach this worker's viewer failed.
    /// `nil` while nothing has failed (no attempt yet, or the last attempt
    /// succeeded), which is what lets the Agents card say "Connecting…"
    /// rather than guessing. Cleared by the engine on a later success.
    let viewerAttachError: String?
    /// Bound work item for this pane. `nil` for ad-hoc / unbound runs.
    let workItemId: String?
    let workItemName: String?
    let workItemShortId: Int?
    /// Product that owns `workItemId`. Needed to reveal the Work card.
    let productId: String?
    /// GitHub PR URL bound to the work item; updates when a PR is opened
    /// mid-run.
    let prURL: String?

    /// Wire value the engine stamps on local workers. Keep in lock-step
    /// with `boss_protocol::LOCAL_HOST_ID`.
    static let localHostId = "local"

    var badgeType: AgentType { AgentType.resolve(wire: agentType, reviewStage: reviewStage, executionKind: executionKind) }
    var badgeLabel: String { badgeType.badgeLabel }

    var agentProject: AgentProject {
        if let projectId, !projectId.isEmpty { return .project(id: projectId) }
        return .unfiled
    }

    var isLocalMember: Bool { hostId == Self.localHostId }

    init(
        name: String? = nil,
        slotId: Int,
        runId: String,
        model: String,
        shellPid: Int32,
        lastEventAt: String?,
        currentTool: String?,
        lastToolEndedAt: String?,
        activity: WorkerActivity,
        liveStatus: String?,
        liveStatusAt: String?,
        recoveryStatus: String?,
        tmuxHosted: Bool?,
        waitReason: String? = nil,
        waitExpiresAt: String? = nil,
        agentType: String? = nil,
        reviewStage: String? = nil,
        executionKind: String? = nil,
        projectId: String? = nil,
        projectName: String? = nil,
        hostId: String? = nil,
        startedAt: String? = nil,
        pool: String? = nil,
        viewerAttachError: String? = nil,
        hungSince: String? = nil,
        workItemId: String? = nil,
        workItemName: String? = nil,
        workItemShortId: Int? = nil,
        productId: String? = nil,
        prURL: String? = nil
    ) {
        self.hungSince = hungSince
        self.name = name
        self.slotId = slotId
        self.runId = runId
        self.model = model
        self.shellPid = shellPid
        self.lastEventAt = lastEventAt
        self.currentTool = currentTool
        self.lastToolEndedAt = lastToolEndedAt
        self.activity = activity
        self.liveStatus = liveStatus
        self.liveStatusAt = liveStatusAt
        self.recoveryStatus = recoveryStatus
        self.tmuxHosted = tmuxHosted
        self.waitReason = waitReason
        self.waitExpiresAt = waitExpiresAt
        self.agentType = agentType
        self.reviewStage = reviewStage
        self.executionKind = executionKind
        self.projectId = projectId
        self.projectName = projectName
        self.hostId = hostId
        self.startedAt = startedAt
        self.pool = pool
        self.viewerAttachError = viewerAttachError
        self.workItemId = workItemId
        self.workItemName = workItemName
        self.workItemShortId = workItemShortId
        self.productId = productId
        self.prURL = prURL
    }

    /// False when two entries share a `runId` or a `slotId`. A snapshot
    /// that fails this is malformed; callers must reject it rather than
    /// building dictionaries with `uniqueKeysWithValues`.
    static func hasUniqueIds(_ states: [WorkerLiveState]) -> Bool {
        var runIds = Set<String>(minimumCapacity: states.count)
        var slotIds = Set<Int>(minimumCapacity: states.count)
        for state in states {
            if !runIds.insert(state.runId).inserted { return false }
            if !slotIds.insert(state.slotId).inserted { return false }
        }
        return true
    }
}

extension WorkerLiveState {
    /// Explicit wait states and legacy idle snapshots with a declared reason
    /// are job waits. A blocking prompt still needs the owner.
    var isWaitingOnJob: Bool {
        activity == .waitingOnWork || activity == .waitOverdue
            || (activity == .idle && !(waitReason ?? "").isEmpty)
    }
}

extension WorkerLiveState: Hashable {
    /// Custom `==`/`hash(into:)` that exclude `lastEventAt` and
    /// `lastToolEndedAt`. Both fields advance on every hook event —
    /// including a pure heartbeat that changes nothing else — so a
    /// synthesized implementation would make two snapshots that differ
    /// only in "when the last event happened" compare unequal. That is
    /// exactly the case `LiveWorkerStateStore.update` relies on this
    /// type's equality to detect and skip, to avoid republishing (and
    /// invalidating every observing card) on every Claude tool call.
    /// Timestamps are still carried on the struct for display — see
    /// `WorkerStalenessIndicator`, which reads `lastEventAt` from
    /// whatever snapshot last actually published and ticks its own
    /// display forward on an independent `TimelineView` timer, so it
    /// does not depend on a fresh publish for every elapsed second.
    static func == (lhs: WorkerLiveState, rhs: WorkerLiveState) -> Bool {
        lhs.name == rhs.name
            && lhs.slotId == rhs.slotId
            && lhs.runId == rhs.runId
            && lhs.model == rhs.model
            && lhs.shellPid == rhs.shellPid
            && lhs.currentTool == rhs.currentTool
            && lhs.activity == rhs.activity
            && lhs.liveStatus == rhs.liveStatus
            && lhs.liveStatusAt == rhs.liveStatusAt
            && lhs.recoveryStatus == rhs.recoveryStatus
            && lhs.hungSince == rhs.hungSince
            && lhs.tmuxHosted == rhs.tmuxHosted
            && lhs.waitReason == rhs.waitReason
            && lhs.waitExpiresAt == rhs.waitExpiresAt
            && lhs.agentType == rhs.agentType
            && lhs.reviewStage == rhs.reviewStage
            && lhs.executionKind == rhs.executionKind
            && lhs.projectId == rhs.projectId
            && lhs.projectName == rhs.projectName
            && lhs.hostId == rhs.hostId
            && lhs.startedAt == rhs.startedAt
            && lhs.pool == rhs.pool
            && lhs.viewerAttachError == rhs.viewerAttachError
            && lhs.workItemId == rhs.workItemId
            && lhs.workItemName == rhs.workItemName
            && lhs.workItemShortId == rhs.workItemShortId
            && lhs.productId == rhs.productId
            && lhs.prURL == rhs.prURL
    }

    func hash(into hasher: inout Hasher) {
        hasher.combine(name)
        hasher.combine(slotId)
        hasher.combine(runId)
        hasher.combine(model)
        hasher.combine(shellPid)
        hasher.combine(currentTool)
        hasher.combine(activity)
        hasher.combine(liveStatus)
        hasher.combine(liveStatusAt)
        hasher.combine(recoveryStatus)
        hasher.combine(hungSince)
        hasher.combine(tmuxHosted)
        hasher.combine(waitReason)
        hasher.combine(waitExpiresAt)
        hasher.combine(agentType)
        hasher.combine(reviewStage)
        hasher.combine(executionKind)
        hasher.combine(projectId)
        hasher.combine(projectName)
        hasher.combine(hostId)
        hasher.combine(startedAt)
        hasher.combine(pool)
        hasher.combine(viewerAttachError)
        hasher.combine(workItemId)
        hasher.combine(workItemName)
        hasher.combine(workItemShortId)
        hasher.combine(productId)
        hasher.combine(prURL)
    }
}

enum WorkerActivity: String, Hashable {
    case spawning
    case working
    case waitingForInput = "waiting_for_input"
    /// Parked on a wait the worker declared itself (`boss propose wait`).
    /// Nobody needs to answer it; the worker re-wakes on its own.
    case waitingOnWork = "waiting_on_work"
    /// The declared wait expired and the worker was not re-woken.
    case waitOverdue = "wait_overdue"
    case idle
    case errored
    case terminated

    /// Short human-readable label suitable for the pane titlebar pill.
    /// We pair this with the model name (e.g., "claude-opus-4-7") so
    /// the user sees both `Claude Opus 4.7 · Working` rather than
    /// the legacy "Agent Unknown".
    var label: String {
        switch self {
        case .spawning: "Spawning"
        case .working: "Working"
        case .waitingForInput: "Waiting"
        case .waitingOnWork: "Waiting on work"
        case .waitOverdue: "Wait overdue"
        case .idle: "Idle"
        case .errored: "Errored"
        case .terminated: "Terminated"
        }
    }

    /// True iff a person is what the worker is blocked on. The single
    /// definition behind the top-bar "Needs input" count and the
    /// "awaiting input" affordances; the engine decides the activity, so the
    /// count, pill and subtitle cannot disagree. A worker parked on its own
    /// declared wait (`waitingOnWork`, `waitOverdue`) is deliberately not one.
    var needsHuman: Bool { self == .waitingForInput }

    /// Agents-pane activity pill. Spawning is a neutral "Starting"; an
    /// engine terminal state is "Exited" until the snapshot releases the run.
    var agentsPaneLabel: String {
        switch self {
        case .spawning: "Starting"
        case .terminated: "Exited"
        default: label
        }
    }
}

enum AgentActivityState: Equatable {
    /// Reason used when a local worker is missing durable tmux identity.
    static let identityUnavailableReason = "Worker pane identity unavailable"

    case active
    case waiting(reason: String)
    /// The worker occupies a slot but has not supplied a hook-derived state.
    /// This is distinct from both working and waiting: after re-adoption the
    /// engine knows the process exists, but not what it is currently doing.
    case unknown(reason: String)
    case errored(reason: String)
    case none
    /// The row is `status=todo, autostart=true` and no worker slot is
    /// free yet. The engine has committed to dispatching it; the pool
    /// is just full. Renders as a hourglass rather than a coloured dot
    /// so it reads as "queued" rather than "active or paused worker".
    case dispatchPending

    /// Build from the persisted task runtime status alone. Used as
    /// the fallback when no LiveWorkerState is available (worker
    /// hasn't emitted any hook events yet, or run is no longer
    /// active).
    init(runtime: WorkTaskRuntime?) {
        guard let runtime, let executionStatus = runtime.executionStatus else {
            self = .none
            return
        }
        switch executionStatus {
        case "running":
            // `running` means the agent is working — the engine is still
            // spawning, or the pane is up and its agent owns the turn loop.
            // Deliberately NOT gated on `runStatus`: the `work_runs` row
            // describes the engine's *spawn* run, which PaneSpawnRunner
            // closes the instant the pane comes up, so a healthy worker
            // spends its whole life as `running` + a closed spawn run.
            // Gating on it here would paint every such worker as "Run
            // completed".
            self = .active
        case "ready":
            self = .waiting(reason: "Queued for a worker")
        case "claimed":
            self = .waiting(reason: "Starting worker")
        case "waiting_human":
            self = .waiting(reason: "Waiting on human input")
        case "waiting_review":
            self = .waiting(reason: "Waiting on review")
        case "waiting_merge":
            self = .waiting(reason: "Waiting on merge")
        case "waiting_dependency":
            self = .waiting(reason: "Waiting on dependency")
        case "failed":
            self = .waiting(reason: "Last run failed")
        case "completed":
            self = .none
        default:
            self = .waiting(reason: executionStatus.replacingOccurrences(of: "_", with: " "))
        }
    }

    /// Build by preferring engine-supplied LiveWorkerState (sourced
    /// from hook events) when available, falling back to the
    /// persisted task runtime status. The dot color now distinguishes
    /// working / waiting-on-input / idle / errored rather than always
    /// rendering the same yellow `running` indicator.
    init(runtime: WorkTaskRuntime?, liveState: WorkerLiveState?) {
        if let liveState {
            if liveState.tmuxHosted == false {
                self = .errored(reason: Self.identityUnavailableReason)
                return
            }
            if liveState.hungSince != nil {
                self = .waiting(reason: "Hung — driver has stopped responding")
                return
            }
            switch liveState.activity {
            case .working:
                self = .active
            case .waitingForInput:
                self = .waiting(reason: "Waiting on user input")
            case .waitingOnWork:
                self = .waiting(reason: Self.waitCaption(liveState))
            case .waitOverdue:
                self = .waiting(reason: Self.overdueCaption(liveState))
            case .idle:
                if liveState.isWaitingOnJob {
                    self = .waiting(reason: Self.waitCaption(liveState))
                } else if let recovering = liveState.recoveryStatus, !recovering.isEmpty {
                    self = .waiting(reason: recovering)
                } else {
                    self = .waiting(reason: "Worker idle between turns")
                }
            case .spawning:
                self = .unknown(reason: "Worker state not yet reported")
            case .errored:
                self = .errored(reason: "Worker reported an error")
            case .terminated:
                self = .none
            }
            return
        }
        self.init(runtime: runtime)
    }

    /// Resolve the activity state for a card in the Doing lane.
    ///
    /// Centralises the precedence rules that previously lived inline in
    /// `WorkBoardCardItem` so they are unit-testable without hosting the
    /// SwiftUI card.
    ///
    /// Precedence:
    /// 1. Dispatch-pending (status=todo, autostart, no slot free yet)
    ///    wins outright — the engine intends to run it but hasn't.
    /// 2. A local worker stamped as not tmux-hosted is unavailable —
    ///    missing identity is an invariant failure, never a supported
    ///    local hosting mode. Remote workers (`tmuxHosted == nil`) skip
    ///    this rule.
    /// 3. Explicit wait states and legacy idle snapshots with a declared
    ///    reason read as waiting, with expired waits called out separately.
    /// 4. A worker paused on a permission prompt
    ///    (`activity == .waitingForInput`, including a prompt raised
    ///    mid-turn while a wait is declared) reads as *waiting on the
    ///    owner*, not active. Without this, the card shows a green
    ///    "working" dot while the run is actually stalled on an input
    ///    prompt no one is watching for. This must precede the bound-slot
    ///    shortcut below; it clears on its own once the worker resumes
    ///    and the activity flips back to `.working`.
    /// 5. A slot-bound worker which has not reported a hook-derived state
    ///    reads as unknown rather than being guessed as active: after
    ///    re-adoption, `.spawning` means the engine knows the process exists
    ///    but not what it is doing.
    /// 6. A bound live worker otherwise reads as active.
    /// 7. Conflict / CI-remediation runs without a bound live worker
    ///    read as their respective "resolving" waits.
    /// 8. Fall back to the runtime+liveState mapping.
    static func forDoingCard(
        runtime: WorkTaskRuntime?,
        liveState: WorkerLiveState?,
        isDispatchPending: Bool,
        isResolvingConflicts: Bool,
        isRemediatingCI: Bool,
        isAIReviewing: Bool = false,
        aiReviewStage: String? = nil
    ) -> AgentActivityState {
        if isDispatchPending {
            return .dispatchPending
        }
        if liveState?.tmuxHosted == false {
            return .errored(reason: Self.identityUnavailableReason)
        }
        if let liveState, liveState.activity == .idle, liveState.isWaitingOnJob {
            return .waiting(reason: waitCaption(liveState))
        }
        if liveState?.activity == .waitingForInput {
            return .waiting(reason: "Waiting on user input")
        }
        if let liveState, liveState.activity == .waitingOnWork {
            return .waiting(reason: waitCaption(liveState))
        }
        if let liveState, liveState.activity == .waitOverdue {
            return .waiting(reason: overdueCaption(liveState))
        }
        if liveState?.activity == .spawning {
            return .unknown(reason: "Worker state not yet reported")
        }
        if liveState?.hungSince != nil {
            return .waiting(reason: "Hung — driver has stopped responding")
        }
        if liveState?.slotId != nil {
            return .active
        }
        if isResolvingConflicts {
            return .waiting(reason: "Resolving merge conflict")
        }
        if isRemediatingCI {
            return .waiting(reason: "Resolving CI failure")
        }
        if isAIReviewing {
            return .waiting(reason: aiReviewCaption(stage: aiReviewStage))
        }
        return AgentActivityState(runtime: runtime, liveState: liveState)
    }

    /// Doing-card caption for a held AI review. The engine reports the stage;
    /// the consolidating agent reads differently from the parallel reviewers.
    static func aiReviewCaption(stage: String?) -> String {
        stage == AgentReviewStage.consolidation ? "Consolidating review findings" : "AI review in progress"
    }

    private static func clockTime(_ iso: String) -> String {
        let parser = ISO8601DateFormatter()
        guard let date = parser.date(from: iso) else { return iso }
        return date.formatted(date: .omitted, time: .shortened)
    }

    static func overdueCaption(_ liveState: WorkerLiveState) -> String {
        overdueCaption(reason: liveState.waitReason)
    }

    static func overdueCaption(reason: String?) -> String {
        let reason = reason ?? "long-running job"
        return "Wait expired without a wake-up: \(reason)"
    }

    static func waitCaption(_ liveState: WorkerLiveState) -> String {
        waitCaption(reason: liveState.waitReason, expiresAt: liveState.waitExpiresAt)
    }

    static func waitCaption(reason: String?, expiresAt: String?) -> String {
        let reason = reason ?? "long-running job"
        if let expiry = expiresAt, !expiry.isEmpty {
            return "Waiting: \(reason) · until \(Self.clockTime(expiry))"
        }
        return "Waiting: \(reason)"
    }

    var tooltip: String {
        switch self {
        case .active:
            return "Agent is actively working"
        case .waiting(let reason):
            return reason
        case .unknown(let reason):
            return reason
        case .errored(let reason):
            return reason
        case .none:
            return "No agent attached"
        case .dispatchPending:
            return "Queued — waiting for a worker slot"
        }
    }
}

extension WorkerActivity {
    /// Keep a narrative summary, but project state literals from current activity.
    func slotSubtitle(prior: String?) -> String? {
        let literals = ["awaiting input", "waiting on its own work", "wait expired — check on it"]
        if let prior, !prior.isEmpty, !literals.contains(prior) {
            return prior
        }
        switch self {
        case .waitingForInput: return literals[0]
        case .waitingOnWork: return literals[1]
        case .waitOverdue: return literals[2]
        default: return nil
        }
    }
}
