//! Single-flight turn queue for the native coordinator chat backend.
//!
//! Even though the ACP adapter advertises `promptQueueing: true`, the engine
//! stays strictly single-flight: once a `session/prompt` is handed to the
//! adapter it can no longer be returned to the composer if the user hits Stop.
//!
//! Ordering and cancellation rules:
//! - One FIFO per origin, with [`PromptOrigin::Engine`] prompts dispatched
//!   ahead of queued [`PromptOrigin::Operator`] prompts.
//! - Engine prompts never pre-empt a turn already in flight.
//! - No prompt is dispatched while an agent-started turn (`async_task_spawned`
//!   with `taskType: "turn"`) is open, or while a `session/prompt` is in flight
//!   or dispatched awaiting wire confirmation.
//! - Stop (`request_stop`) cancels only the active turn: every still-queued
//!   operator prompt is drained in FIFO order to be returned to the composer as
//!   a draft, while queued engine prompts stay in the queue and proceed once
//!   the cancelled turn completes.

use boss_acp_client::schema::RequestId;
use boss_protocol::{CoordinatorChatMessageRole, CoordinatorChatTurnOrigin};
use serde::{Deserialize, Serialize};

/// Who authored a prompt entering the coordinator's turn queue.
///
/// Agent-started turns (background agent completion, peer inbox messages) do
/// not enter the prompt queue; they are tracked as open agent turns instead.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum PromptOrigin {
    /// Typed or sent by the user from the app.
    Operator,
    /// Generated by the engine (session-start brief, prompt-changed nudge,
    /// reset request, or handoff write authorization).
    Engine,
}

impl PromptOrigin {
    /// Message role shown in the conversation timeline for prompts of this origin.
    pub fn message_role(self) -> CoordinatorChatMessageRole {
        match self {
            Self::Operator => CoordinatorChatMessageRole::Operator,
            Self::Engine => CoordinatorChatMessageRole::Engine,
        }
    }

    /// Turn boundary origin recorded for turns triggered by prompts of this origin.
    pub fn turn_origin(self) -> CoordinatorChatTurnOrigin {
        match self {
            Self::Operator => CoordinatorChatTurnOrigin::Human,
            Self::Engine => CoordinatorChatTurnOrigin::Engine,
        }
    }
}

/// Reference to an image file stored in the coordinator generation directory
/// and attached to a queued/sent prompt.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PromptImageRef {
    /// Path relative to the coordinator generation directory (for example
    /// `images/img-001.png`).
    pub path: String,
    /// Validated MIME type sent in the ACP `image` content block.
    pub mime_type: String,
    /// Original filename if supplied by the app.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub filename: Option<String>,
    /// File size in bytes when recorded.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub byte_len: Option<u64>,
}

/// Text and stored image references carried by a queued or in-flight prompt.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PromptContent {
    /// Raw prompt text (redacted whenever projected outside the engine).
    pub text: String,
    /// Stored image references attached to this prompt.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub images: Vec<PromptImageRef>,
}

/// One prompt waiting in the turn queue to be sent as `session/prompt`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct QueuedPrompt {
    /// Unique, monotonic identifier assigned when the prompt was recorded in
    /// the generation's intent log.
    pub intent_id: u64,
    /// Whether this prompt came from the user (`Operator`) or the engine.
    pub origin: PromptOrigin,
    /// Prompt payload (text and attached image references).
    #[serde(flatten)]
    pub content: PromptContent,
    /// Optional app-assigned id for correlating pending composer messages.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub client_message_id: Option<String>,
    /// Wall-clock milliseconds when the prompt was queued.
    pub queued_ts_ms: u64,
}

impl QueuedPrompt {
    /// Raw prompt text.
    pub fn text(&self) -> &str {
        &self.content.text
    }

    /// Stored image references attached to this prompt.
    pub fn images(&self) -> &[PromptImageRef] {
        &self.content.images
    }
}

/// A prompt that has been dispatched as `session/prompt` and has not yet
/// received its JSON-RPC response.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct InFlightPrompt {
    pub prompt: QueuedPrompt,
    pub request_id: RequestId,
    pub sent_ts_ms: u64,
    /// Wire-journal sequence number of the `ToAgent` `session/prompt` record
    /// once observed in the journal.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub wire_seq: Option<u64>,
}

/// Result of pressing Stop on the turn queue.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StopOutcome {
    /// True when the caller should answer pending permissions as cancelled and
    /// send `session/cancel` on the wire (an active turn exists and cancel has
    /// not already been requested for it).
    pub send_cancel: bool,
    /// True when a turn (prompt or agent-started) is currently active.
    pub active_turn: bool,
    /// Queued operator prompts removed from the queue in FIFO order so the app
    /// can return them to the composer as a draft.
    pub returned_operator_prompts: Vec<QueuedPrompt>,
}

/// Single-flight coordinator turn queue state machine.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct TurnQueue {
    /// Queued prompts in exact dispatch order: all `Engine` prompts in FIFO
    /// order followed by all `Operator` prompts in FIFO order.
    #[serde(default)]
    queued: Vec<QueuedPrompt>,
    /// The single prompt currently in flight on the wire.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    in_flight: Option<InFlightPrompt>,
    /// Prompts recorded as `Sent` in the intent log whose `ToAgent`
    /// `session/prompt` record has not yet been observed in the wire journal.
    ///
    /// Kept as a FIFO list rather than a map so two prompts that happened to
    /// reuse a numeric `RequestId` across an engine restart still match their
    /// wire records in order during replay.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    dispatched_awaiting_wire: Vec<InFlightPrompt>,
    /// Currently open agent-started turns (`async_task_spawned` with
    /// `taskType: "turn"`).
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    open_agent_turns: Vec<String>,
    /// True after Stop / `session/cancel` until the active turn closes.
    #[serde(default)]
    cancel_requested: bool,
}

impl TurnQueue {
    pub fn new() -> Self {
        Self::default()
    }

    /// Prompts waiting to be sent, in dispatch order (engine FIFO, then
    /// operator FIFO).
    pub fn queued(&self) -> &[QueuedPrompt] {
        &self.queued
    }

    /// Number of prompts currently waiting to be sent.
    pub fn queued_len(&self) -> usize {
        self.queued.len()
    }

    /// The prompt currently in flight on the wire, if any.
    pub fn in_flight(&self) -> Option<&InFlightPrompt> {
        self.in_flight.as_ref()
    }

    /// Prompts recorded as `Sent` in the intent log that have not yet appeared
    /// in the wire journal.
    pub fn dispatched_awaiting_wire(&self) -> &[InFlightPrompt] {
        &self.dispatched_awaiting_wire
    }

    /// Currently open agent-started turn task ids.
    pub fn open_agent_turns(&self) -> &[String] {
        &self.open_agent_turns
    }

    /// True when either a `session/prompt` is in flight on the wire or an
    /// agent-started turn is open.
    pub fn has_active_turn(&self) -> bool {
        self.in_flight.is_some() || !self.open_agent_turns.is_empty()
    }

    /// True when the queue cannot dispatch another prompt (active turn on the
    /// wire, open agent-started turn, or a prompt already dispatched awaiting
    /// wire confirmation).
    pub fn is_busy(&self) -> bool {
        self.has_active_turn() || !self.dispatched_awaiting_wire.is_empty()
    }

    /// True when the session is idle and at least one prompt is waiting to be
    /// sent.
    pub fn can_send(&self) -> bool {
        !self.is_busy() && !self.queued.is_empty()
    }

    /// True while cancellation has been requested for the active turn.
    pub fn cancel_requested(&self) -> bool {
        self.cancel_requested
    }

    /// Returns the next prompt eligible to send right now, or `None` if the
    /// session is busy or the queue is empty.
    pub fn peek_next_dispatchable(&self) -> Option<&QueuedPrompt> {
        if self.is_busy() {
            return None;
        }
        self.queued.first()
    }

    /// Adds `prompt` to the queue.
    ///
    /// Engine prompts are placed after any existing queued engine prompts and
    /// ahead of all queued operator prompts; operator prompts are appended at
    /// the tail. Duplicate `intent_id`s already queued, dispatched, or in
    /// flight are ignored so replay is idempotent.
    pub fn enqueue(&mut self, prompt: QueuedPrompt) {
        if self.contains_intent_id(prompt.intent_id) {
            return;
        }
        match prompt.origin {
            PromptOrigin::Engine => {
                let idx = self
                    .queued
                    .iter()
                    .take_while(|existing| existing.origin == PromptOrigin::Engine)
                    .count();
                self.queued.insert(idx, prompt);
            }
            PromptOrigin::Operator => {
                self.queued.push(prompt);
            }
        }
    }

    /// Pops the next dispatchable prompt and marks it directly in flight.
    ///
    /// Returns `None` if a turn is already active, a dispatch is awaiting wire
    /// confirmation, or the queue is empty.
    pub fn begin_send(&mut self, request_id: RequestId, sent_ts_ms: u64) -> Option<InFlightPrompt> {
        if !self.can_send() {
            return None;
        }
        let prompt = self.queued.remove(0);
        let entry = InFlightPrompt {
            prompt,
            request_id,
            sent_ts_ms,
            wire_seq: None,
        };
        self.cancel_requested = false;
        self.in_flight = Some(entry.clone());
        Some(entry)
    }

    /// Transitions a queued prompt to dispatched-awaiting-wire when
    /// `IntentRecord::Sent` is applied.
    ///
    /// Keeping dispatched entries separate from `in_flight` lets replay apply
    /// all intent records before (or interleaved with) wire records while still
    /// keeping live dispatch strictly single-flight (`is_busy()` is true while
    /// any entry awaits its wire echo).
    ///
    /// If `intent_id` is already in `dispatched_awaiting_wire`, the new `Sent`
    /// record supersedes the abandoned earlier dispatch attempt (for example
    /// when a previous engine crashed before the host journalled the first
    /// attempt and a restarted engine retried the same intent under a new
    /// `request_id`).
    pub fn mark_intent_sent(
        &mut self,
        intent_id: u64,
        request_id: RequestId,
        sent_ts_ms: u64,
    ) -> Option<InFlightPrompt> {
        let prompt = if let Some(pos) = self.queued.iter().position(|entry| entry.intent_id == intent_id) {
            self.queued.remove(pos)
        } else {
            let pos = self
                .dispatched_awaiting_wire
                .iter()
                .position(|entry| entry.prompt.intent_id == intent_id)?;
            self.dispatched_awaiting_wire.remove(pos).prompt
        };
        let entry = InFlightPrompt {
            prompt,
            request_id,
            sent_ts_ms,
            wire_seq: None,
        };
        self.dispatched_awaiting_wire.push(entry.clone());
        Some(entry)
    }

    /// Binds a `ToAgent` `session/prompt` wire record to its dispatched intent.
    ///
    /// Matches the earliest `dispatched_awaiting_wire` entry carrying
    /// `request_id` (FIFO), moves it to `in_flight` with `wire_seq`, and
    /// returns it. If `in_flight` already carries `request_id` without a
    /// `wire_seq` (for callers that drove [`Self::begin_send`] directly), its
    /// `wire_seq` is filled in and returned.
    pub fn on_wire_prompt_sent(&mut self, request_id: &RequestId, wire_seq: u64) -> Option<InFlightPrompt> {
        if let Some(pos) = self
            .dispatched_awaiting_wire
            .iter()
            .position(|entry| request_ids_equal(&entry.request_id, request_id))
        {
            let was_idle = !self.has_active_turn();
            let mut entry = self.dispatched_awaiting_wire.remove(pos);
            entry.wire_seq = Some(wire_seq);
            if was_idle {
                self.cancel_requested = false;
            }
            self.in_flight = Some(entry.clone());
            return Some(entry);
        }
        if let Some(active) = &mut self.in_flight
            && request_ids_equal(&active.request_id, request_id)
        {
            if active.wire_seq.is_none() {
                active.wire_seq = Some(wire_seq);
            }
            return Some(active.clone());
        }
        None
    }

    /// Completes the in-flight prompt when its `FromAgent` JSON-RPC response
    /// arrives on the wire.
    pub fn on_wire_prompt_finished(&mut self, request_id: &RequestId) -> Option<InFlightPrompt> {
        let matches = self
            .in_flight
            .as_ref()
            .is_some_and(|active| request_ids_equal(&active.request_id, request_id));
        if !matches {
            return None;
        }
        let finished = self.in_flight.take();
        if !self.has_active_turn() {
            self.cancel_requested = false;
        }
        finished
    }

    /// Opens an agent-started turn (`async_task_spawned` with
    /// `taskType: "turn"`). No queued prompt will be dispatched while any such
    /// turn remains open.
    pub fn on_agent_turn_started(&mut self, task_id: impl Into<String>) {
        let task_id = task_id.into();
        if !self.open_agent_turns.iter().any(|existing| existing == &task_id) {
            if !self.has_active_turn() {
                self.cancel_requested = false;
            }
            self.open_agent_turns.push(task_id);
        }
    }

    /// Closes an agent-started turn (`async_task_state_update` with
    /// `completed`, `failed`, or `stopped`).
    pub fn on_agent_turn_finished(&mut self, task_id: &str) -> bool {
        let Some(pos) = self.open_agent_turns.iter().position(|existing| existing == task_id) else {
            return false;
        };
        self.open_agent_turns.remove(pos);
        if !self.has_active_turn() {
            self.cancel_requested = false;
        }
        true
    }

    /// Withdraws a prompt that is still waiting in the queue.
    ///
    /// Returns `None` if `intent_id` is already in flight, already dispatched
    /// to the adapter, or unknown.
    pub fn withdraw(&mut self, intent_id: u64) -> Option<QueuedPrompt> {
        let pos = self.queued.iter().position(|entry| entry.intent_id == intent_id)?;
        Some(self.queued.remove(pos))
    }

    /// Withdraws a queued prompt matching `client_message_id`.
    pub fn withdraw_by_client_message_id(&mut self, client_message_id: &str) -> Option<QueuedPrompt> {
        let pos = self
            .queued
            .iter()
            .position(|entry| entry.client_message_id.as_deref() == Some(client_message_id))?;
        Some(self.queued.remove(pos))
    }

    /// Withdraws every still-queued prompt matching `predicate`, returning them
    /// in queue order. Never touches an in-flight prompt.
    pub fn withdraw_where(&mut self, mut predicate: impl FnMut(&QueuedPrompt) -> bool) -> Vec<QueuedPrompt> {
        let mut withdrawn = Vec::new();
        let mut kept = Vec::with_capacity(self.queued.len());
        for entry in self.queued.drain(..) {
            if predicate(&entry) {
                withdrawn.push(entry);
            } else {
                kept.push(entry);
            }
        }
        self.queued = kept;
        withdrawn
    }

    /// Applies a `Requeued` intent-log record during live or replay processing.
    ///
    /// Removes `intent_id` from `dispatched_awaiting_wire` and re-inserts it
    /// into `queued` preserving origin/intent order, abandoning the unsent
    /// attempt so it cannot bind a subsequent wire prompt. Never touches a
    /// prompt that is already `in_flight` on the wire.
    pub(crate) fn apply_requeued_intent(&mut self, intent_id: u64) -> Option<QueuedPrompt> {
        let pos = self
            .dispatched_awaiting_wire
            .iter()
            .position(|entry| entry.prompt.intent_id == intent_id)?;
        let prompt = self.dispatched_awaiting_wire.remove(pos).prompt;
        self.insert_preserving_origin_intent_order(prompt.clone());
        Some(prompt)
    }

    /// Applies a `Withdrawn` intent-log record during live or replay processing.
    ///
    /// Removes the prompt from `queued`, or from `dispatched_awaiting_wire` if
    /// it was withdrawn after a crash before ever reaching the wire. Never
    /// removes a prompt that is already `in_flight` on the wire.
    pub(crate) fn apply_withdrawn_intent(&mut self, intent_id: u64) -> Option<QueuedPrompt> {
        if let Some(prompt) = self.withdraw(intent_id) {
            return Some(prompt);
        }
        let pos = self
            .dispatched_awaiting_wire
            .iter()
            .position(|entry| entry.prompt.intent_id == intent_id)?;
        Some(self.dispatched_awaiting_wire.remove(pos).prompt)
    }

    /// Computes the [`StopOutcome`] without mutating the queue.
    ///
    /// Useful when the caller wants to persist `IntentRecord::Withdrawn`
    /// records before mutating reducer state via `apply_intent_record`.
    pub fn plan_stop(&self) -> StopOutcome {
        let active_turn = self.is_busy();
        let send_cancel = active_turn && !self.cancel_requested;
        let returned_operator_prompts = self
            .queued
            .iter()
            .filter(|entry| entry.origin == PromptOrigin::Operator)
            .cloned()
            .collect();
        StopOutcome {
            send_cancel,
            active_turn,
            returned_operator_prompts,
        }
    }

    /// Handles the user pressing Stop.
    ///
    /// - Marks cancel requested for the active turn (whether prompt-initiated
    ///   or agent-started) so `send_cancel` is true once per turn.
    /// - Removes every still-queued `Operator` prompt in FIFO order and returns
    ///   them so they can be restored to the composer as a draft.
    /// - Keeps every queued `Engine` prompt in the queue to run once the
    ///   cancelled turn finishes.
    pub fn request_stop(&mut self) -> StopOutcome {
        let active_turn = self.is_busy();
        let send_cancel = active_turn && !self.cancel_requested;
        if active_turn {
            self.cancel_requested = true;
        }
        let returned_operator_prompts = self.withdraw_where(|entry| entry.origin == PromptOrigin::Operator);
        StopOutcome {
            send_cancel,
            active_turn,
            returned_operator_prompts,
        }
    }

    /// Records that `session/cancel` was observed going out on the wire.
    ///
    /// Ignored when no turn is currently active so a stray or late cancel
    /// (for example racing a turn's completion) cannot suppress Stop on the
    /// next turn.
    pub fn note_wire_cancel_sent(&mut self) {
        if self.has_active_turn() {
            self.cancel_requested = true;
        }
    }

    /// Re-queues any prompts whose `IntentRecord::Sent` was logged before an
    /// engine crash but never reached the wire journal.
    ///
    /// Call this only after replaying the full wire journal tail up to the
    /// agent host's live boundary. Re-queued prompts are inserted by
    /// `intent_id` order within their origin group (engine ahead of operator)
    /// so original FIFO order is preserved relative to prompts queued later.
    pub fn recover_unsent_dispatches(&mut self) -> Vec<QueuedPrompt> {
        if self.dispatched_awaiting_wire.is_empty() {
            return Vec::new();
        }
        let mut recovered: Vec<QueuedPrompt> = self
            .dispatched_awaiting_wire
            .drain(..)
            .map(|entry| entry.prompt)
            .collect();
        recovered.sort_by_key(|prompt| prompt.intent_id);
        for prompt in &recovered {
            self.insert_preserving_origin_intent_order(prompt.clone());
        }
        recovered
    }

    fn insert_preserving_origin_intent_order(&mut self, prompt: QueuedPrompt) {
        if self.contains_intent_id(prompt.intent_id) {
            return;
        }
        let idx = match prompt.origin {
            PromptOrigin::Engine => self
                .queued
                .iter()
                .take_while(|existing| existing.origin == PromptOrigin::Engine && existing.intent_id < prompt.intent_id)
                .count(),
            PromptOrigin::Operator => {
                let engine_count = self
                    .queued
                    .iter()
                    .take_while(|existing| existing.origin == PromptOrigin::Engine)
                    .count();
                let op_offset = self.queued[engine_count..]
                    .iter()
                    .take_while(|existing| existing.intent_id < prompt.intent_id)
                    .count();
                engine_count + op_offset
            }
        };
        self.queued.insert(idx, prompt);
    }

    fn contains_intent_id(&self, intent_id: u64) -> bool {
        self.queued.iter().any(|entry| entry.intent_id == intent_id)
            || self
                .dispatched_awaiting_wire
                .iter()
                .any(|entry| entry.prompt.intent_id == intent_id)
            || self
                .in_flight
                .as_ref()
                .is_some_and(|active| active.prompt.intent_id == intent_id)
    }
}

pub(crate) fn request_ids_equal(a: &RequestId, b: &RequestId) -> bool {
    // Compare canonical JSON forms so numeric `1` never matches string `"1"`.
    match (serde_json::to_string(a), serde_json::to_string(b)) {
        (Ok(left), Ok(right)) => left == right,
        _ => a == b,
    }
}
